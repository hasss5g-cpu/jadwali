import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, locale: "ar-SA" });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", (e) => errors.push(e.message));
page.on("response", (r) => { if (r.status() >= 400) errors.push(`HTTP ${r.status()} ${r.url()}`); });
await page.goto("https://hasss5g-cpu.github.io/jadwali/", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
const title = await page.title();
const cards = await page.locator(".kpi-value").count();
await page.getByRole("button", { name: "الجدول", exact: true }).click();
await page.waitForTimeout(600);
const cells = await page.locator(".schedule-cell").count();
await page.screenshot({ path: "docs/screenshots/live-schedule.png" });
await page.goto("https://hasss5g-cpu.github.io/jadwali/#/classes", { waitUntil: "networkidle" });
await page.waitForTimeout(500);
const classLinks = await page.locator('a[href^="#/class/"]').count();
console.log(JSON.stringify({ title, kpiCards: cards, scheduleCells: cells, classLinks, errors }, null, 1));
await browser.close();
